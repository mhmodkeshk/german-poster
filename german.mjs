async function post() {
  const today = new Date();
  const start = new Date(today.getFullYear(), 0, 0);
  const dayOfYear = Math.floor((today - start) / 86400000);
  const dayIndex = dayOfYear % messages.length;
  const message = messages[dayIndex];

  const imageUrl = 'https://raw.githubusercontent.com/mhmodkeshk/german-poster/main/german.jpg';
  const url = `https://graph.facebook.com/v19.0/${FB_PAGE_ID}/photos`;

  const res = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ url: imageUrl, message, access_token: FB_ACCESS_TOKEN }),
  });

  const data = await res.json();
  if (data.id) {
    console.log(`✅ Posted! Day ${dayOfYear} - Post ID: ${data.id}`);
  } else {
    console.error('❌ Failed:', JSON.stringify(data));
    process.exit(1);
  }
}

